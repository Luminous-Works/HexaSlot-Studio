export function buildPresetSlots(presetId: string): InsertSlotState[] {
  const preset = RACK_PRESETS.find((p) => p.id === presetId) ?? RACK_PRESETS[0];
  const slots: InsertSlotState[] = Array.from({ length: 16 }, (_, idx) => createDefaultSlot(idx, 'empty'));
  for (const item of preset.slots) {
    if (item.index >= 0 && item.index < 16) {
      slots[item.index] = {
        index: item.index,
        moduleId: item.moduleId,
        bypassed: Boolean(item.bypassed),
        mix: item.mix,
        p1: item.p1,
        p2: item.p2,
        p3: item.p3,
        p4: item.p4,
      };
    }
  }
  return slots;
}

