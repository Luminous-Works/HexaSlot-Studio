export function computeEuclideanPattern(steps: number, pulses: number, rotation: number): boolean[] {
  const s = Math.max(1, Math.min(16, Math.round(steps)));
  const p = Math.max(0, Math.min(s, Math.round(pulses)));
  const pattern: boolean[] = Array.from({ length: s }, (_, i) => {
    if (p === 0) return false;
    return Math.floor(((i + 1) * p) / s) > Math.floor((i * p) / s);
  });
  const rot = ((rotation % s) + s) % s;
  return pattern.map((_, idx) => pattern[(idx - rot + s) % s]);
}

