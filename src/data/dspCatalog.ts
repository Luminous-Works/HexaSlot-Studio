export function createDefaultSlot(index: number, moduleId: DspModuleId = 'empty'): InsertSlotState {
  const spec = DSP_MODULES[moduleId];
  return {
    index,
    moduleId,
    bypassed: false,
    mix: moduleId === 'empty' ? 100 : 75,
    p1: spec.params[0]?.defaultValue ?? 0,
    p2: spec.params[1]?.defaultValue ?? 0,
    p3: spec.params[2]?.defaultValue ?? 0,
    p4: spec.params[3]?.defaultValue ?? 0,
  };
}

